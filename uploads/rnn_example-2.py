def predict_custom_review(review_text, model, max_features=10000, max_len=100):
    words = review_text.lower().split()
    encoded_review = []
    for word in words:
        index = word_index.get(word, None)
        if index is not None and (index + 3) < max_features:
            encoded_review.append(index + 3)
        else:
            encoded_review.append(2)  #(Out-of-vocabulary)

    padded_review = sequence.pad_sequences([encoded_review], maxlen=max_len)

    prediction = model.predict(padded_review, verbose=0)[0][0]

    sentiment = "Positive Review" if prediction >= 0.5 else "Negative Review (బాగాలేదు / నెగటివ్)"
    confidence = prediction if prediction >= 0.5 else (1 - prediction)

    print(f"\nReview: '{review_text}'")
    print(f"Prediction Score: {prediction:.4f}")
    print(f"Result: {sentiment} (Confidence: {confidence * 100:.2f}%)")

